#!/usr/bin/env python3
"""Write the Discord link preview (a component embed) into the <head> of every page in site/.

Run from anywhere: python scripts/build-discord-embeds.py [--check]
Each page gets one <script id="discord:component-embed" type="application/json"> line, built
from the page's own <title>, description and URL, so re-run this after changing a page's title
or description, or after adding a page (and after scripts/build-sitemap.py, which rebuilds the
sitemap page from the legal hub). --check changes nothing and exits 1 if any page is out of date.

The home page, /docs/, /changelogs/ and the legal hub get their own previews; every other page
gets the generic one (its name and description, with a way back to the home page). 404.html gets
none. When a payload would be over Discord's 3,000-byte limit the page gets an HTML comment
instead, and Discord falls back to the Open Graph tags, which every page keeps.
Spec: https://docs.discord.com/developers/link-previews/component-embeds

Copyright (c) 2026 Stux.Group. All Rights Reserved.
"""
import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / "site"
BASE_URL = "https://githup.stux.group"
SITE_NAME = "GitHup"
ICON = BASE_URL + "/assets/icon.png"
ACCENT = "#8f7dff"  # GitHup's brand accent (the demo's accent in .githup.yml)
MAX_BYTES = 3000
GITHUB = "https://github.com/StuxGroup/GitHup"

# Pages that never get a preview: error pages.
SKIP = {"404.html"}

COMMENT = "<!-- Discord: a custom link preview (the Open Graph tags are its fallback). Generated by scripts/build-discord-embeds.py. -->"
BLOCK_RE = re.compile(r'^(?:<!-- Discord: [^\n]*-->\n)?(?:<script id="discord:component-embed"[^\n]*</script>|<!-- discord:component-embed [^\n]*-->)\n', re.M)


def discord_md(s: str) -> str:
    """Escapes Discord markdown so data (titles, descriptions) shows as plain text."""
    # Inline formatting, link brackets and backslashes anywhere; headings, quotes and lists only at a line start.
    s = re.sub(r"([\\*_~`|\[\]])", r"\\\1", s)
    return re.sub(r"^([#>-])", r"\\\1", s, flags=re.M)


def text(markdown: str) -> dict:
    return {"type": 10, "content": markdown}


def buttons(links: list) -> dict:
    """A row of link buttons from (label, absolute URL) pairs."""
    return {"type": 1, "components": [{"type": 2, "style": 5, "label": label[:80], "url": url} for label, url in links]}


def section(markdown: str) -> dict:
    """Text with the GitHup icon beside it."""
    return {"type": 9, "components": [text(markdown)], "accessory": {"type": 11, "media": {"url": ICON}}}


def payload(components: list, accent: str = ACCENT):
    """The JSON for the <script>, or None when it's over Discord's 3,000-byte limit."""
    data = {"component": {"type": 17, "accent_color": int(accent.lstrip("#"), 16), "components": components}}
    out = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    out = out.replace("<", "\\u003c")  # data can't close the <script> (or open a comment) early
    return None if len(out.encode("utf-8")) > MAX_BYTES else out


def embed(components: list, accent: str = ACCENT) -> str:
    out = payload(components, accent)
    if out is None:
        return f"<!-- discord:component-embed left out: over {MAX_BYTES} bytes -->"
    return f'<script id="discord:component-embed" type="application/json">{out}</script>'


def site_label() -> str:
    """The small "GitHup" line above a page's title (Discord subtext), like a normal preview's site name."""
    return f"-# [{SITE_NAME}]({BASE_URL}/)\n"


def home_embed(title: str, desc: str, url: str) -> str:
    """The home page: what GitHup is, the key facts, and the way to the demo and docs."""
    return embed([
        section(f"# [{SITE_NAME}]({url})\n**Uptime monitoring and a status page, run entirely on GitHub.**\n" + discord_md(desc)),
        {"type": 14},
        text("Checks every 5 minutes · History committed to your repo · Outages open Issues · Status page on GitHub Pages\n"
             "-# No servers. No dependencies. MIT licensed. A Stux.Group Service."),
        buttons([("Live demo", BASE_URL + "/demo/"), ("Docs", BASE_URL + "/docs/"), ("GitHub", GITHUB)]),
    ])


def docs_embed(title: str, desc: str, url: str) -> str:
    return embed([
        section(site_label() + f"## [{discord_md(title)}]({url})\n{discord_md(desc)}\n"
                "-# GitHup's README from the v1 tag, the release every @v1 workflow runs"),
        buttons([("Read the docs", url), ("Quick start", BASE_URL + "/#start"), ("GitHub", GITHUB)]),
    ])


def changelogs_embed(title: str, desc: str, url: str) -> str:
    url = BASE_URL + "/changelogs/"  # /changelog/ redirects here
    return embed([
        section(site_label() + f"## [{discord_md(title)}]({url})\n{discord_md(desc)}\n"
                "-# Every release of the website and of the GitHup action, newest first"),
        buttons([("Website", url + "#website"), ("GitHup action", url + "#githup"), ("Releases on GitHub", GITHUB + "/releases")]),
    ])


LEGAL_PAGES = [("Privacy Policy", "privacy"), ("Terms and Ethics", "terms"), ("Cookies Policy", "cookies"),
               ("Imprint", "imprint"), ("Disclaimer", "disclaimer"), ("Opt-Out Preferences", "opt-out")]


def legal_embed(title: str, desc: str, url: str) -> str:
    links = " · ".join(f"[{name}]({BASE_URL}/legal/{slug}/)" for name, slug in LEGAL_PAGES)
    return embed([
        section(site_label() + f"## [{discord_md(title)}]({url})\n{discord_md(desc)}"),
        text(links),
        buttons([("Open", url), (f"{SITE_NAME} home", BASE_URL + "/")]),
    ])


def page_embed(title: str, desc: str, url: str) -> str:
    """Any other page: its name and description, with a way back to the home page."""
    return embed([
        section(site_label() + f"## [{discord_md(title)}]({url})\n{discord_md(desc)}"),
        buttons([("Open", url), (f"{SITE_NAME} home", BASE_URL + "/")]),
    ])


BUILDERS = {"/": home_embed, "/docs/": docs_embed, "/changelogs/": changelogs_embed, "/legal/": legal_embed}


def _attr(page: str, pattern: str) -> str:
    m = re.search(pattern, page)
    return html.unescape(m.group(1)) if m else ""


def meta(page: str) -> dict:
    title = _attr(page, r"<title>([^<]*)</title>")
    return {
        "title": re.sub(r" · GitHup$", "", title),
        "desc": _attr(page, r'<meta name="description" content="([^"]*)"'),
        "url": _attr(page, r'<meta property="og:url" content="([^"]*)"') or _attr(page, r'<link rel="canonical" href="([^"]*)"'),
    }


def pages() -> list:
    return [p for p in sorted(SITE.rglob("*.html")) if p.relative_to(SITE).as_posix() not in SKIP]


def build(page: str, descs: dict) -> str:
    """Returns the page with its embed block written (or replaced) in <head>."""
    m = meta(page)
    path = m["url"][len(BASE_URL):] if m["url"].startswith(BASE_URL) else "/"
    desc = m["desc"] or descs.get(m["url"], "")  # a redirect page borrows its target's description
    block = COMMENT + "\n" + BUILDERS.get(path, page_embed)(m["title"], desc, m["url"]) + "\n"
    page = BLOCK_RE.sub("", page)
    for anchor in ('<meta name="twitter:card" content="summary_large_image">\n', '<meta name="robots" content="noindex">\n'):
        if anchor in page:
            return page.replace(anchor, anchor + block, 1)
    return page.replace("</title>\n", "</title>\n" + block, 1)


def main() -> int:
    check = "--check" in sys.argv[1:]
    sources = {p: p.read_text(encoding="utf-8") for p in pages()}
    descs = {meta(t)["url"]: meta(t)["desc"] for t in sources.values() if meta(t)["desc"]}
    stale = []
    for p, before in sources.items():
        after = build(before, descs)
        if after != before:
            stale.append(p.relative_to(ROOT).as_posix())
            if not check:
                p.write_text(after, encoding="utf-8", newline="\n")
    if check:
        if stale:
            print("Out of date (run python scripts/build-discord-embeds.py): " + ", ".join(stale))
            return 1
        print(f"Discord embeds up to date ({len(sources)} pages)")
        return 0
    print(f"Wrote Discord embeds into {len(stale)} of {len(sources)} pages")
    return 0


if __name__ == "__main__":
    sys.exit(main())
